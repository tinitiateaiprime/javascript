/*
  This lesson explains JavaScript var.
  var is the old way to create variables.
*/

/*
  We can store values inside variables.
*/

var courseName = "JavaScript";

/*
  var variables can change later.
*/

var score = 10;

score = 20;

// Print variable values.

console.log(courseName);

console.log(score);

/*
  We can store text with var.
*/

var studentName = "Asha";

console.log(studentName);

/*
  We can store numbers with var.
*/

var age = 22;

console.log(age);

/*
  We can print multiple var values together.
*/

console.log(studentName, age);

/*
  var can store math results too.
*/

var total = 10 + 5;

console.log(total);

/*
  We can change var values again.
*/

var city = "Hyderabad";

city = "Vijayawada";

console.log(city);

/*
  var is still used in old JavaScript code.
*/

// Warning message.

console.warn("var is old style JavaScript");

// Error message.

console.error("Example error message");

