// This lesson explains JavaScript comments.
// Comments help humans read code.

// JavaScript ignores comments when the file runs.


// This is a single-line comment.

console.log("JS Comments");

// This is a multi-line comment.
// It can take more than one line.


console.log("Comments explain code for humans.");

// This prints text in the terminal or browser console.

console.log("JavaScript ignores comments.");

// We can place comments before code.

// Print a number.

console.log(100);

// Print math output.

console.log(10 + 20);

// Print text and numbers together.

console.log("Age:", 22);

//  Comments are useful for beginners.
//  They explain what the code does.

// Warning message.

console.warn("This is warning");

// Error message.

console.error("Something went wrong");