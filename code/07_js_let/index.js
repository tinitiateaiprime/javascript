// JavaScript: let Keyword Tutorial
// =================================

// This lesson explains JavaScript let.
// let is used when a value can change later.

// We can store values inside variables.

let attempts = 1;

// Print the starting value.

console.log(attempts);

//  let values can change later.

attempts = attempts + 1;

// Print the updated value.

console.log(attempts);

// We can store text with let.

let studentName = "Asha";

console.log(studentName);

// let can store numbers too.  

let score = 10;

console.log(score);

// We can change let values.

score = 20;

console.log(score);

 // let is useful for counters and totals.

let total = 5;

total = total + 5;

console.log(total);

 // We can print multiple let values together.

console.log(studentName, score);

// let is commonly used in modern JavaScript.

// Warning message.

console.warn("let values can change");

// Error message.

console.error("Example error message");

